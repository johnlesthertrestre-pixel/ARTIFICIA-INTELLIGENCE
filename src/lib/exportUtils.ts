import JSZip from 'jszip';
import { AppForgePlan } from '../types/forge';

export async function downloadProjectZip(plan: AppForgePlan) {
  const zip = new JSZip();

  // Root files
  zip.file(
    'README.md',
    `# ${plan.appName}

> ${plan.tagline}

Generated by **AppForge AI** — Intelligent Application Architecture & Scaffolding Engine.

## Overview
${plan.overview}

## Architecture
- **Client**: ${plan.architecture.client}
- **Server**: ${plan.architecture.server}
- **Database**: ${plan.architecture.database}
- **Authentication**: ${plan.architecture.authMethod}
- **Hosting**: ${plan.architecture.hosting}

## Quick Start
\`\`\`bash
# 1. Install dependencies
npm install

# 2. Launch development server
npm run dev

# 3. Execute test suite
npm test
\`\`\`

## High Priority Requirements (P0)
${plan.requirements.p0.map(req => `- [ ] ${req}`).join('\n')}

## Security & Edge Cases
${plan.riskAndEdgeCases.map(r => `### ${r.title} (${r.severity} Severity)
- **Impact**: ${r.impact}
- **Mitigation**: ${r.mitigationStrategy}
`).join('\n')}
`
  );

  // Schema folder
  const schemaFolder = zip.folder('schema');
  if (schemaFolder) {
    schemaFolder.file('schema.sql', plan.databaseSchema.sqlDdl || '-- SQL DDL');
    if (plan.databaseSchema.prismaSchema) {
      schemaFolder.file('schema.prisma', plan.databaseSchema.prismaSchema);
    }
    schemaFolder.file('types.ts', plan.databaseSchema.typescriptInterfaces || '');
    if (plan.databaseSchema.seedDataJson) {
      schemaFolder.file('seed.json', plan.databaseSchema.seedDataJson);
    }
  }

  // Starter code files
  for (const file of plan.starterCode.files) {
    zip.file(file.path, file.content);
  }

  // PRD Specification
  zip.file('SPEC_PRD.md', generateMarkdownPrd(plan));

  // QA & Tests
  const testsFolder = zip.folder('tests');
  if (testsFolder) {
    testsFolder.file(
      'QA_CHECKLIST.md',
      `# QA Production Readiness Checklist for ${plan.appName}\n\n` +
        plan.testPlan.qaChecklist
          .map(
            q =>
              `- [ ] **[${q.priority}]** (${q.category}) ${q.item}`
          )
          .join('\n')
    );
  }

  // Generate blob and trigger download
  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${plan.appName.toLowerCase().replace(/[^a-z0-9]/g, '-')}-starter.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function generateMarkdownPrd(plan: AppForgePlan): string {
  return `# Product Requirements Document (PRD)
# ${plan.appName}
*${plan.tagline}*

---

## 1. Executive Summary
${plan.overview}

### Target Audience & Personas
${plan.targetAudience.map(aud => `- ${aud}`).join('\n')}

---

## 2. Technical Architecture
| Component | Specification |
| :--- | :--- |
| **Client** | ${plan.architecture.client} |
| **Server** | ${plan.architecture.server} |
| **Database** | ${plan.architecture.database} |
| **Auth** | ${plan.architecture.authMethod} |
| **Hosting** | ${plan.architecture.hosting} |

### Third-Party Services
${plan.architecture.keyThirdPartyServices?.map(s => `- ${s}`).join('\n') || 'None specified'}

---

## 3. Product Requirements
### P0 (Must Have - MVP)
${plan.requirements.p0.map(r => `- [ ] ${r}`).join('\n')}

### P1 (Should Have - Fast Follow)
${plan.requirements.p1.map(r => `- [ ] ${r}`).join('\n')}

${
  plan.requirements.p2 && plan.requirements.p2.length > 0
    ? `### P2 (Nice to Have)
${plan.requirements.p2.map(r => `- [ ] ${r}`).join('\n')}`
    : ''
}

### Non-Functional Requirements (SLAs)
${plan.requirements.nonFunctional.map(n => `- ${n}`).join('\n')}

---

## 4. User Stories & Acceptance Criteria
${plan.userStories
  .map(
    s => `### ${s.id}: ${s.persona}
**As a** ${s.persona},
**I want to** ${s.want},
**So that** ${s.soThat}.

**Acceptance Criteria:**
${s.acceptanceCriteria.map(ac => `- ${ac}`).join('\n')}
`
  )
  .join('\n')}

---

## 5. Risk & Security Edge Cases
${plan.riskAndEdgeCases
  .map(
    r => `### [${r.severity.toUpperCase()}] ${r.title}
- **Category**: ${r.category}
- **Impact**: ${r.impact}
- **Mitigation**: ${r.mitigationStrategy}
`
  )
  .join('\n')}
`;
}

export function downloadTextFile(filename: string, content: string, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
